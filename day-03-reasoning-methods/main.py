# Импортируем модуль os для чтения переменных окружения.
import os

# Импортируем модуль time, чтобы при необходимости поставить программу на паузу.
import time

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv

# Импортируем основной клиент для обращения к Groq API.
from groq import Groq


# Загружаем переменные окружения из файла .env в память программы.
load_dotenv()

# Получаем значение переменной GROQ_API_KEY.
api_key = os.getenv("GROQ_API_KEY")

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        # Первая часть сообщения об ошибке.
        "Переменная GROQ_API_KEY не найдена. "
        # Вторая часть сообщения объясняет, что нужно сделать.
        "Добавьте API-ключ в файл .env"
    )

# Создаём клиент Groq и передаём ему API-ключ для авторизации запросов.
client = Groq(api_key=api_key)

# Указываем модель, которая будет выполнять все задания.
MODEL = "openai/gpt-oss-20b"

# Ограничиваем максимальное количество токенов одного ответа.
MAX_COMPLETION_TOKENS = 2048

# Указываем продолжительность паузы после достижения лимита Groq API.
RATE_LIMIT_WAIT_SECONDS = 60

# Создаём общий системный промпт, который используется во всех запросах.
SYSTEM_PROMPT = (
    # Задаём имя и роль модели.
    "Ты бортовой помощник космического корабля по имени Бублик. "
    # Сообщаем модели имя пользователя.
    "Пользователя зовут Чебуратор. "
    # Добавляем контекст общения.
    "Он космический путешественник, который ищет "
    # Продолжаем предыдущую строку системного промпта.
    "приключения в галактике. "
    # Указываем язык ответа.
    "Отвечай ему на русском языке."
)

# Сохраняем условие логической задачи в отдельной константе.
TASK = (
    # Описываем основную цель задачи.
    "Четырём исследователям нужно ночью перейти мост. "
    # Указываем скорость каждого исследователя.
    "Они переходят мост за 1, 2, 7 и 10 минут соответственно. "
    # Устанавливаем ограничение на количество людей на мосту.
    "Одновременно на мосту могут находиться не более двух человек, "
    # Объясняем правило использования фонаря.
    "у группы есть один фонарь, а без фонаря идти нельзя. "
    # Объясняем, как рассчитывается время перехода пары.
    "Когда идут двое, они движутся со скоростью более медленного. "
    # Задаём вопрос, на который должна ответить модель.
    "Какое минимальное время потребуется, чтобы все перешли мост?"
)


# Объявляем функцию, которая отправляет один промпт модели и возвращает ответ.
def get_response(user_prompt: str) -> str:
    # Даём запросу две попытки: первоначальную и одну повторную после лимита API.
    for attempt in range(2):
        # Начинаем блок, в котором может возникнуть ошибка API.
        try:
            # Отправляем запрос в Chat Completions API.
            response = client.chat.completions.create(
                # Передаём идентификатор выбранной модели.
                model=MODEL,
                # Формируем список сообщений, которые получит модель.
                messages=[
                    # Первое сообщение задаёт общие правила поведения модели.
                    {
                        # Роль system имеет более высокий приоритет, чем user.
                        "role": "system",
                        # Передаём текст общего системного промпта.
                        "content": SYSTEM_PROMPT,
                    },
                    # Второе сообщение содержит конкретное текущее задание.
                    {
                        # Роль user обозначает запрос пользователя.
                        "role": "user",
                        # Передаём текст, полученный через параметр функции.
                        "content": user_prompt,
                    },
                ],
                # Низкая температура делает ответы стабильнее и точнее.
                temperature=0.2,
                # Низкий reasoning effort уменьшает расход внутренних токенов.
                reasoning_effort="low",
                # Ограничиваем генерацию с учётом тарифного лимита 8000 TPM.
                max_completion_tokens=MAX_COMPLETION_TOKENS,
            )

            # Берём текст первого варианта ответа или пустую строку вместо None.
            return response.choices[0].message.content or ""

        # Перехватываем ошибку, возникшую во время обращения к API.
        except Exception as error:
            # Проверяем, связана ли ошибка с ограничением количества запросов или токенов.
            is_rate_limit_error = (
                # Groq может вернуть статус 413 или 429 при превышении лимита.
                getattr(error, "status_code", None) in {413, 429}
                # Дополнительно проверяем внутренний код ошибки в её тексте.
                and "rate_limit_exceeded" in str(error)
            )

            # Не повторяем неизвестную ошибку или уже провалившуюся вторую попытку.
            if not is_rate_limit_error or attempt == 1:
                # Передаём ошибку во внешний блок обработки без изменений.
                raise

            # Сообщаем пользователю, почему выполнение временно остановилось.
            print(
                # Первая часть сообщения о достигнутом лимите.
                "\nДостигнут лимит Groq API. "
                # Вторая часть сообщения показывает продолжительность ожидания.
                f"Повторный запрос через {RATE_LIMIT_WAIT_SECONDS} секунд..."
            )

            # Ждём освобождения минутного лимита перед повторной попыткой.
            time.sleep(RATE_LIMIT_WAIT_SECONDS)

    # Защитная ошибка: при нормальной работе выполнение до этой строки не дойдёт.
    raise RuntimeError("Не удалось получить ответ модели")


# Объявляем вспомогательную функцию для красивого вывода разделов в консоль.
def print_section(title: str, content: str) -> None:
    # Печатаем пустую строку и верхний разделитель длиной 70 символов.
    print("\n" + "=" * 70)

    # Печатаем заголовок раздела.
    print(title)

    # Печатаем нижний разделитель длиной 70 символов.
    print("=" * 70)

    # Печатаем основное содержимое раздела.
    print(content)


# Объявляем главную функцию программы.
def main() -> None:
    # Печатаем название практического задания.
    print("🤖 День 3 — разные способы рассуждения")

    # Показываем условие задачи перед получением решений.
    print_section("ЗАДАЧА", TASK)

    # Способ 1: отправляем только условие задачи без дополнительных инструкций.
    direct_answer = get_response(TASK)

    # Выводим прямой ответ модели.
    print_section("1. ПРЯМОЙ ОТВЕТ", direct_answer)

    # Способ 2: добавляем явную инструкцию рассуждать пошагово.
    step_by_step_answer = get_response(
        # Объединяем условие задачи и дополнительную инструкцию в один промпт.
        f"{TASK}\n\nРешай пошагово. Проверь итоговый ответ."
    )

    # Выводим пошаговое решение модели.
    print_section("2. ПОШАГОВОЕ РЕШЕНИЕ", step_by_step_answer)

    # Способ 3, этап 1: просим модель самостоятельно создать хороший промпт.
    generated_prompt = get_response(
        # Объясняем модели, какой текст она должна подготовить.
        "Составь точный и понятный промпт для решения следующей "
        # Указываем обязательное наличие исходной задачи в новом промпте.
        "логической задачи. Промпт должен содержать саму задачу, "
        # Требуем не только ответ, но и проверку его оптимальности.
        "попросить найти минимальное время и проверить оптимальность "
        # Добавляем формат результата и исходное условие задачи.
        f"решения. Верни только готовый промпт.\n\nЗадача:\n{TASK}"
    )

    # Показываем промпт, который самостоятельно составила модель.
    print_section("3.1. ПРОМПТ, СОСТАВЛЕННЫЙ МОДЕЛЬЮ", generated_prompt)

    # Способ 3, этап 2: отправляем созданный промпт обратно модели.
    generated_prompt_answer = get_response(generated_prompt)

    # Выводим решение, полученное с помощью созданного промпта.
    print_section(
        # Передаём заголовок раздела первым аргументом.
        "3.2. РЕШЕНИЕ ПО СОСТАВЛЕННОМУ ПРОМПТУ",
        # Передаём ответ модели вторым аргументом.
        generated_prompt_answer,
    )

    # Способ 4: просим трёх виртуальных экспертов независимо разобрать задачу.
    experts_answer = get_response(
        # Сначала передаём экспертам исходное условие задачи.
        f"{TASK}\n\n"
        # Просим каждого эксперта представить отдельное решение.
        "Решите задачу группой из трёх экспертов. Каждый должен дать "
        # Завершаем вводную инструкцию и начинаем список ролей.
        "своё решение отдельно:\n"
        # Аналитик должен рассмотреть несколько стратегий.
        "1. Аналитик — найдёт возможные стратегии и выберет лучшую.\n"
        # Инженер должен проверить последовательность действий и арифметику.
        "2. Инженер — распишет последовательность переходов и вычисления.\n"
        # Критик должен найти возможные ошибки и проверить минимальность.
        "3. Критик — проверит решение, найдёт ошибки и оценит, доказан ли минимум."
    )

    # Выводим ответы группы экспертов.
    print_section("4. ГРУППА ЭКСПЕРТОВ", experts_answer)

    # Создаём отдельный запрос для сравнения четырёх полученных решений.
    comparison = get_response(
        # Объясняем модели её новую задачу — сравнить ответы.
        "Сравни четыре решения одной логической задачи. "
        # Передаём правильный результат только оценщику, а не решающим моделям.
        "Правильный минимальный результат — 17 минут. Корректный маршрут: "
        # Передаём первую часть эталонного маршрута.
        "1 и 2 переходят, 1 возвращается, 7 и 10 переходят, "
        # Передаём вторую часть эталонного маршрута.
        "2 возвращается, 1 и 2 переходят. "
        # Устанавливаем критерии сравнения ответов.
        "Для каждого способа оцени правильность ответа, ясность объяснения "
        # Просим проверить доказательство минимальности и выбрать лучший способ.
        "и наличие проверки минимальности. Затем назови наиболее точный "
        # Запрещаем оценивать точность только по объёму ответа.
        "и убедительный способ. Не оценивай длину текста как признак точности."
        # Добавляем к промпту прямой ответ.
        f"\n\n1. Прямой ответ:\n{direct_answer}"
        # Добавляем к промпту пошаговое решение.
        f"\n\n2. Пошаговое решение:\n{step_by_step_answer}"
        # Добавляем решение по созданному моделью промпту.
        f"\n\n3. Решение по составленному промпту:\n{generated_prompt_answer}"
        # Добавляем ответ группы экспертов.
        f"\n\n4. Группа экспертов:\n{experts_answer}"
    )

    # Выводим итоговое сравнение всех способов.
    print_section("ИТОГОВОЕ СРАВНЕНИЕ", comparison)


# Проверяем, был ли файл запущен напрямую, а не импортирован как модуль.
if __name__ == "__main__":
    # Начинаем общий блок обработки ошибок программы.
    try:
        # Запускаем главную функцию.
        main()

    # Перехватываем ошибку, которую не удалось обработать внутри get_response.
    except Exception as error:
        # Показываем пользователю понятное сообщение вместо полного traceback.
        print(f"\nОшибка при обращении к LLM: {error}\n")