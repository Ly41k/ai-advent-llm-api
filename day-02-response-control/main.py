# Импортируем модуль os для чтения переменных окружения.
import os

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv

# Импортируем основной клиент для обращения к Groq API.
from groq import Groq


# Загружаем переменные из файла .env в окружение программы.
load_dotenv()

# Получаем API-ключ из переменной окружения GROQ_API_KEY.
api_key = os.getenv("GROQ_API_KEY")

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        # Первая часть сообщения сообщает, какая переменная не найдена.
        "Переменная GROQ_API_KEY не найдена. "
        # Вторая часть сообщения объясняет, куда нужно добавить ключ.
        "Добавьте API-ключ в файл .env"
    )

# Создаём клиент Groq и передаём ему API-ключ для авторизации запросов.
client = Groq(api_key=api_key)

# Создаём основной системный промпт, общий для обоих вариантов запроса.
SYSTEM_PROMPT = (
    # Задаём имя и роль модели.
    "Ты бортовой помощник космического корабля по имени Бублик. "
    # Сообщаем модели имя пользователя.
    "Пользователя зовут Чебуратор. "
    # Добавляем контекст общения с пользователем.
    "Он космический путешественник, который ищет "
    # Продолжаем предыдущую строку системного промпта.
    "приключения в галактике. "
    # Указываем язык, на котором модель должна отвечать.
    "Отвечай ему на русском языке."
)

# Создаём дополнительные правила для ответа с ограничениями.
CONTROL_INSTRUCTIONS = (
    # Добавляем две пустые строки и заголовок блока правил.
    "\n\nПравила ответа:\n"
    # Требуем начинать ответ с определённой строки.
    "1. Начни со строки «Краткий ответ:».\n"
    # Устанавливаем точную структуру маркированного списка.
    "2. Затем напиши ровно три пункта маркированного списка.\n"
    # Ограничиваем видимую длину ответа семьюдесятью словами.
    "3. Используй не более 70 слов.\n"
    # Указываем момент, в котором модель должна завершить ответ.
    "4. Заверши ответ сразу после третьего пункта.\n"
    # Запрещаем добавлять заключение и другой текст после списка.
    "5. Не добавляй заключение или дополнительный текст."
)


# Объявляем функцию, которая отправляет один запрос модели.
def get_response(user_input: str, with_limits: bool = False) -> str:
    # Создаём локальную копию основного системного промпта.
    system_prompt = SYSTEM_PROMPT

    # Проверяем, нужно ли добавить правила управления ответом.
    if with_limits:
        # Добавляем правила формата, длины и завершения ответа.
        system_prompt += CONTROL_INSTRUCTIONS

    # Собираем параметры API-запроса в отдельный словарь.
    request_parameters = {
        # Указываем модель, которая должна обработать запрос.
        "model": "openai/gpt-oss-20b",
        # Создаём список сообщений, передаваемых модели.
        "messages": [
            # Первым передаём системное сообщение с правилами поведения.
            {
                # Роль system задаёт общие инструкции для модели.
                "role": "system",
                # Используем обычный или дополненный системный промпт.
                "content": system_prompt,
            },
            # Вторым передаём сообщение пользователя.
            {
                # Роль user обозначает пользовательский запрос.
                "role": "user",
                # В content сохраняем введённый пользователем текст.
                "content": user_input,
            },
        ],
        # Настраиваем вариативность и творческую свободу ответа.
        "temperature": 0.8,
        # Используем небольшой объём внутренних рассуждений модели.
        "reasoning_effort": "low",
    }

    # Проверяем, выполняется ли запрос с ограничениями.
    if with_limits:
        # Добавляем технический лимит генерации только контролируемому запросу.
        request_parameters["max_completion_tokens"] = 500

    # Раскрываем словарь через ** и передаём его элементы как аргументы функции.
    response = client.chat.completions.create(**request_parameters)

    # Возвращаем текст первого ответа или пустую строку вместо None.
    return response.choices[0].message.content or ""


# Выводим в консоль название программы.
print("🤖 Сравнение форматов ответа")

# Объясняем пользователю, как завершить программу.
print("Введите «выход» для завершения.\n")

# Запускаем бесконечный цикл для обработки нескольких запросов пользователя.
while True:
    # Показываем приглашение «Вы:», читаем ввод и удаляем пробелы по краям.
    user_input = input("Вы: ").strip()

    # Проверяем, ввёл ли пользователь команду завершения.
    if user_input.lower() == "выход":
        # Печатаем прощальное сообщение.
        print("До свидания!")

        # Прерываем бесконечный цикл и завершаем программу.
        break

    # Проверяем, осталась ли строка пустой после удаления пробелов.
    if not user_input:
        # Пропускаем текущую итерацию и снова ожидаем пользовательский ввод.
        continue

    # Начинаем блок обработки возможных ошибок API.
    try:
        # Выполняем первый запрос без дополнительных ограничений.
        response_without_limits = get_response(
            # Передаём текст, введённый пользователем.
            user_input=user_input,
            # Отключаем добавление управляющих инструкций.
            with_limits=False,
        )

        # Выполняем второй запрос с тем же пользовательским текстом.
        response_with_limits = get_response(
            # Передаём тот же запрос для честного сравнения результатов.
            user_input=user_input,
            # Включаем формат, ограничение длины и условие завершения.
            with_limits=True,
        )

        # Печатаем пустую строку и верхний разделитель первого ответа.
        print("\n" + "=" * 50)

        # Печатаем заголовок ответа без ограничений.
        print("БЕЗ ОГРАНИЧЕНИЙ")

        # Печатаем нижний разделитель заголовка.
        print("=" * 50)

        # Выводим текст первого ответа модели.
        print(response_without_limits)

        # Печатаем пустую строку и верхний разделитель второго ответа.
        print("\n" + "=" * 50)

        # Печатаем заголовок ответа с ограничениями.
        print("С ОГРАНИЧЕНИЯМИ")

        # Печатаем нижний разделитель заголовка.
        print("=" * 50)

        # Выводим текст второго ответа модели.
        print(response_with_limits)

        # Добавляем пустые строки после результатов для читаемости.
        print("\n")

    # Перехватываем любую ошибку, возникшую при обращении к API.
    except Exception as error:
        # Выводим понятное сообщение с текстом полученной ошибки.
        print(f"\nОшибка при обращении к LLM: {error}\n")
