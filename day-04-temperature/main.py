# Импортируем модуль os для чтения переменных окружения.
import os

# Импортируем модуль time, чтобы при необходимости поставить программу на паузу.
import time

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv

# Импортируем основной клиент для обращения к Groq API.
from groq import Groq


# Загружаем переменные окружения из файла .env в память программы.
load_dotenv()

# Получаем API-ключ из переменной окружения GROQ_API_KEY.
api_key = os.getenv("GROQ_API_KEY")

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        # Первая часть сообщения сообщает, какая переменная не найдена.
        "Переменная GROQ_API_KEY не найдена. "
        # Вторая часть сообщения объясняет, куда нужно добавить ключ.
        "Добавьте API-ключ в файл .env"
    )

# Создаём клиент Groq и передаём ему API-ключ для авторизации запросов.
client = Groq(api_key=api_key)

# Указываем модель, которая будет выполнять все запросы эксперимента.
MODEL = "openai/gpt-oss-20b"

# Сохраняем три значения температуры, которые необходимо сравнить.
TEMPERATURES = (0.0, 0.7, 1.2)

# Ограничиваем максимальное количество токенов одного ответа.
MAX_COMPLETION_TOKENS = 1200

# Указываем продолжительность паузы после достижения лимита Groq API.
RATE_LIMIT_WAIT_SECONDS = 60

# Создаём общий системный промпт, одинаковый для всех запросов.
SYSTEM_PROMPT = (
    # Задаём имя и роль модели.
    "Ты бортовой помощник космического корабля по имени Бублик. "
    # Сообщаем модели имя пользователя.
    "Пользователя зовут Чебуратор. "
    # Добавляем контекст общения с пользователем.
    "Он космический путешественник, который ищет "
    # Продолжаем предыдущую строку системного промпта.
    "приключения в галактике. "
    # Указываем язык, на котором модель должна отвечать.
    "Отвечай ему на русском языке."
)

# Создаём пользовательский запрос, одинаковый для трёх значений температуры.
TASK = (
    # Просим модель придумать основную концепцию робота.
    "Придумай концепцию автономного робота для исследования "
    # Указываем место и условия предполагаемой миссии.
    "подлёдного океана Европы — спутника Юпитера. "
    # Перечисляем обязательные элементы ответа.
    "Укажи название робота, цель миссии, три технически "
    # Продолжаем список обязательных элементов ответа.
    "правдоподобные функции и короткий слоган. "
    # Требуем отделять предположения от подтверждённых фактов.
    "Не выдавай предположения за подтверждённые факты."
)


# Объявляем функцию, которая отправляет один запрос модели.
def get_response(user_prompt: str, temperature: float) -> str:
    # Добавляем краткое описание назначения функции.
    """Отправляет запрос модели с указанной температурой."""

    # Даём запросу две попытки: первоначальную и повторную после лимита API.
    for attempt in range(2):
        # Начинаем блок, в котором может возникнуть ошибка API.
        try:
            # Отправляем запрос в Chat Completions API.
            response = client.chat.completions.create(
                # Передаём идентификатор выбранной модели.
                model=MODEL,
                # Формируем список сообщений, которые получит модель.
                messages=[
                    # Первым добавляем системное сообщение.
                    {
                        # Роль system определяет общие правила поведения модели.
                        "role": "system",
                        # Передаём общий системный промпт.
                        "content": SYSTEM_PROMPT,
                    },
                    # Вторым добавляем сообщение пользователя.
                    {
                        # Роль user обозначает конкретный пользовательский запрос.
                        "role": "user",
                        # Передаём текст, полученный через параметр функции.
                        "content": user_prompt,
                    },
                ],
                # Передаём температуру текущего этапа эксперимента.
                temperature=temperature,
                # Используем небольшой объём внутренних рассуждений модели.
                reasoning_effort="low",
                # Ограничиваем максимальное количество токенов генерации.
                max_completion_tokens=MAX_COMPLETION_TOKENS,
            )

            # Возвращаем текст первого ответа или пустую строку вместо None.
            return response.choices[0].message.content or ""

        # Перехватываем ошибку, возникшую при обращении к API.
        except Exception as error:
            # Проверяем, связана ли ошибка с лимитом запросов или токенов.
            is_rate_limit_error = (
                # Groq может вернуть статус 413 или 429 при превышении лимита.
                getattr(error, "status_code", None) in {413, 429}
                # Дополнительно проверяем внутренний код ошибки в её тексте.
                and "rate_limit_exceeded" in str(error)
            )

            # Не повторяем неизвестную ошибку или провалившуюся вторую попытку.
            if not is_rate_limit_error or attempt == 1:
                # Передаём ошибку во внешний обработчик без изменений.
                raise

            # Сообщаем пользователю, почему выполнение временно остановилось.
            print(
                # Первая часть сообщения о достигнутом лимите.
                "\nДостигнут лимит Groq API. "
                # Вторая часть сообщения показывает продолжительность ожидания.
                f"Повторный запрос через {RATE_LIMIT_WAIT_SECONDS} секунд..."
            )

            # Ждём освобождения минутного лимита перед повторной попыткой.
            time.sleep(RATE_LIMIT_WAIT_SECONDS)

    # Защитная ошибка: при нормальной работе выполнение сюда не дойдёт.
    raise RuntimeError("Не удалось получить ответ модели")


# Объявляем вспомогательную функцию для красивого вывода разделов.
def print_section(title: str, content: str) -> None:
    # Добавляем краткое описание назначения функции.
    """Выводит отдельный этап эксперимента в консоль."""

    # Печатаем пустую строку и верхний разделитель длиной 70 символов.
    print("\n" + "=" * 70)

    # Печатаем заголовок текущего раздела.
    print(title)

    # Печатаем нижний разделитель заголовка.
    print("=" * 70)

    # Печатаем основное содержимое раздела.
    print(content)


# Объявляем функцию для подготовки промпта итогового сравнения.
def build_comparison_prompt(responses: dict[float, str]) -> str:
    # Добавляем краткое описание назначения функции.
    """Формирует запрос для сравнения трёх полученных ответов."""

    # Объединяем ответы в один текст и подписываем их температурой.
    answers = "\n\n".join(
        # Формируем отдельный блок для одной температуры и её ответа.
        f"TEMPERATURE = {temperature:g}\n{response}"
        # Перебираем все сохранённые температуры и ответы.
        for temperature, response in responses.items()
    )

    # Возвращаем готовый промпт для модели-оценщика.
    return (
        # Объясняем оценщику его основную задачу.
        "Сравни три ответа на один и тот же запрос. "
        # Указываем три обязательных критерия оценки.
        "Оцени каждый по точности, креативности и разнообразию идей. "
        # Определяем, что именно в эксперименте считается точностью.
        "Точность означает соблюдение задания, внутреннюю логичность и "
        # Продолжаем определение критерия точности.
        "отсутствие неподтверждённых утверждений, выданных за факты. "
        # Запрещаем считать объём текста самостоятельным признаком качества.
        "Не считай длинный ответ автоматически более качественным. "
        # Требуем сначала представить результаты в компактной таблице.
        "Сначала составь компактную таблицу. Затем сформулируй вывод, "
        # Просим подобрать задачи для каждого значения температуры.
        "для каких задач лучше подходят temperature 0, 0.7 и 1.2. "
        # Напоминаем об ограниченной достоверности единичного эксперимента.
        "Учитывай, что один запуск показывает пример поведения, "
        # Завершаем предупреждение об интерпретации результатов.
        "а не гарантированный результат всех будущих запросов."
        # Добавляем к промпту исходный пользовательский запрос.
        f"\n\nИСХОДНЫЙ ЗАПРОС:\n{TASK}"
        # Добавляем три ответа, которые необходимо сравнить.
        f"\n\nОТВЕТЫ:\n{answers}"
    )


# Объявляем главную функцию программы.
def main() -> None:
    # Печатаем название практического задания.
    print("🤖 День 4 — влияние температуры")

    # Показываем одинаковый запрос перед началом эксперимента.
    print_section("ОДИНАКОВЫЙ ЗАПРОС", TASK)

    # Создаём словарь для хранения ответа при каждой температуре.
    responses: dict[float, str] = {}

    # Последовательно перебираем три заданных значения температуры.
    for temperature in TEMPERATURES:
        # Выполняем исходный запрос с текущей температурой.
        response = get_response(
            # Передаём одинаковый пользовательский запрос.
            user_prompt=TASK,
            # Передаём текущее значение температуры.
            temperature=temperature,
        )

        # Сохраняем полученный ответ под соответствующей температурой.
        responses[temperature] = response

        # Выводим ответ текущего этапа в отдельном разделе.
        print_section(
            # Добавляем значение температуры в заголовок раздела.
            f"TEMPERATURE = {temperature:g}",
            # Передаём полученный текст для вывода.
            response,
        )

    # Выполняем дополнительный запрос для сравнения трёх результатов.
    comparison = get_response(
        # Создаём промпт на основе сохранённых ответов.
        user_prompt=build_comparison_prompt(responses),
        # Используем нулевую температуру для более стабильной оценки.
        temperature=0.0,
    )

    # Выводим итоговое сравнение и рекомендации по использованию температур.
    print_section("СРАВНЕНИЕ И ВЫВОДЫ", comparison)


# Проверяем, был ли файл запущен напрямую, а не импортирован как модуль.
if __name__ == "__main__":
    # Начинаем общий блок обработки ошибок программы.
    try:
        # Запускаем главную функцию.
        main()

    # Перехватываем ошибку, которую не удалось обработать внутри get_response.
    except Exception as error:
        # Показываем пользователю понятное сообщение вместо полного traceback.
        print(f"\nОшибка при обращении к LLM: {error}\n")

