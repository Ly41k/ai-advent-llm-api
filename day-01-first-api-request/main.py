# Импортируем модуль os для чтения переменных окружения.
import os

# Импортируем функцию, которая загружает переменные из файла .env.
from dotenv import load_dotenv

# Импортируем основной клиент для обращения к Groq API.
from groq import Groq


# Загружаем переменные из файла .env в окружение программы.
load_dotenv()

# Получаем API-ключ из переменной окружения GROQ_API_KEY.
api_key = os.getenv("GROQ_API_KEY")

# Проверяем, удалось ли найти API-ключ.
if not api_key:
    # Останавливаем программу и показываем понятную ошибку, если ключ отсутствует.
    raise RuntimeError(
        # Первая часть сообщения сообщает, какая переменная не найдена.
        "Переменная GROQ_API_KEY не найдена. "
        # Вторая часть сообщения объясняет, куда нужно добавить ключ.
        "Добавьте API-ключ в файл .env"
    )

# Создаём клиент Groq и передаём ему API-ключ для авторизации запросов.
client = Groq(api_key=api_key)

# Создаём список, в котором будет храниться история текущего диалога.
messages = [
    # Первым элементом добавляем системное сообщение с правилами для модели.
    {
        # Роль system определяет поведение модели на протяжении диалога.
        "role": "system",
        # Поле content содержит текст системной инструкции.
        "content": (
            # Задаём имя и роль модели.
            "Ты бортовой помощник космического корабля по имени Бублик. "
            # Сообщаем модели имя пользователя.
            "Пользователя зовут Чебуратор. "
            # Добавляем контекст общения с пользователем.
            "Он космический путешественник, который ищет "
            # Продолжаем предыдущую строку системного промпта.
            "приключения в галактике. "
            # Указываем язык, на котором модель должна отвечать.
            "Отвечай ему на русском языке."
        ),
    }
]

# Выводим в консоль название программы.
print("🤖 Чат-бот на Groq")

# Объясняем пользователю, как завершить программу.
print("Введите «выход» для завершения.\n")

# Запускаем бесконечный цикл, чтобы пользователь мог отправлять много сообщений.
while True:
    # Показываем приглашение «Вы:», читаем ввод и удаляем пробелы по краям.
    user_input = input("Вы: ").strip()

    # Проверяем, ввёл ли пользователь команду завершения.
    if user_input.lower() == "выход":
        # Печатаем прощальное сообщение.
        print("До свидания!")

        # Прерываем бесконечный цикл и завершаем программу.
        break

    # Проверяем, осталась ли строка пустой после удаления пробелов.
    if not user_input:
        # Пропускаем текущую итерацию и снова ожидаем пользовательский ввод.
        continue

    # Добавляем новое сообщение пользователя в историю диалога.
    messages.append(
        # Создаём объект сообщения в формате, ожидаемом Groq API.
        {
            # Роль user обозначает сообщение пользователя.
            "role": "user",
            # В content сохраняем введённый пользователем текст.
            "content": user_input,
        }
    )

    # Начинаем блок обработки возможных ошибок при обращении к API.
    try:
        # Отправляем системный промпт и всю историю диалога модели.
        response = client.chat.completions.create(
            # Указываем модель, которая должна обработать запрос.
            model="openai/gpt-oss-20b",
            # Передаём полный список сообщений текущего диалога.
            messages=messages,
            # Настраиваем вариативность и творческую свободу ответа.
            temperature=0.8,
            # Устанавливаем средний объём внутренних рассуждений модели.
            reasoning_effort="medium",
        )

        # Получаем текст первого варианта ответа или пустую строку вместо None.
        bot_response = response.choices[0].message.content or ""

        # Добавляем успешный ответ модели в историю диалога.
        messages.append(
            # Создаём объект сообщения ассистента.
            {
                # Роль assistant обозначает ответ языковой модели.
                "role": "assistant",
                # В content сохраняем текст ответа модели.
                "content": bot_response,
            }
        )

        # Выводим ответ модели и добавляем пустую строку для читаемости.
        print(f"Бот: {bot_response}\n")

    # Перехватываем любую ошибку, возникшую при обращении к API.
    except Exception as error:
        # Удаляем последнее сообщение пользователя, на которое модель не ответила.
        messages.pop()

        # Выводим понятное сообщение с текстом полученной ошибки.
        print(f"Ошибка при обращении к LLM: {error}\n")
